"""Writes compositions/tunnel.html: a corridor of video cards the camera flies down.

Eye-level cards alternate walls every 306.5 px of depth; the eight feature cards sit where the camera
passes them as their word lands (dolly 1173 px/s, prominent at 420 px in front of the lens).
usage: python3 -I capture/tunnel.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
B = 0.5221
SPEED, LEAD = 1173, 420
WALL_X, WALL_R = 700, 62

FEATURES = [  # word, time (local s), card kind
    ("Loop.", B * 4), ("Mark.", B * 4.5), ("Boost.", B * 5), ("Speed.", B * 5.5),
    ("Dim.", B * 6), ("Tint.", B * 6.5), ("Snap.", B * 7), ("Float.", B * 7.5),
]
STILLS = [f"assets/stills/s{i:02d}.jpg" for i in range(1, 13)]

BAR = '<div class="bar"><i style="width:{w}%"></i></div>'
UI = {
    "Loop.": BAR.format(w=38) + '<div class="edit"><div class="range"><b class="h1"></b><b class="h2"></b></div></div>',
    "Mark.": BAR.format(w=44) + '<div class="marker"></div><div class="pill" style="left:96px;bottom:30px">'
    '<svg viewBox="0 0 24 24" fill="none" stroke="#38d9ff" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round">'
    '<path d="M17 3a2 2 0 0 1 2 2v15a1 1 0 0 1-1.496.868l-4.512-2.578a2 2 0 0 0-1.984 0l-4.512 2.578A1 1 0 0 1 5 20V5a2 2 0 0 1 2-2z"/></svg>'
    "Bookmark this moment</div>",
    "Boost.": BAR.format(w=52) + '<div class="vol"><i></i></div><div class="pill" style="right:58px;bottom:58px">Volume boost <b>5×</b></div>',
    "Speed.": BAR.format(w=58) + '<div class="chip" style="right:16px;top:16px">'
    '<svg viewBox="0 0 24 24" fill="none" stroke="#fff" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round">'
    '<path d="m12 14 4-4"/><path d="M3.34 19a10 10 0 1 1 17.32 0"/></svg>2×</div>',
    "Dim.": '<div class="chip" style="left:16px;top:16px">Cinema Mode</div>',
    "Tint.": BAR.format(w=63) + '<div class="chip" style="left:16px;top:16px">Mono</div>',
    "Snap.": BAR.format(w=67) + '<div class="flash"></div><div class="pill" style="left:150px;bottom:30px">'
    '<img src="assets/stills/s14.jpg" alt="">Screenshot saved.</div>',
    "Float.": "",
}
IMG = {"Loop.": "s03", "Mark.": "s04", "Boost.": "s05", "Speed.": "s12", "Dim.": "s11", "Tint.": "s13-mono", "Snap.": "s14", "Float.": "s10"}


def card(x, y, z, r, inner, cls="card"):
    return f'<div class="{cls}" style="transform:translate3d({x}px,{y}px,{z}px) rotateY({r}deg)">{inner}</div>'


cards = []
z_first = -(SPEED * FEATURES[0][1] + LEAD)
step = (SPEED * (FEATURES[1][1] - FEATURES[0][1]))
for j in range(15):  # 7 plain cards, then the 8 features, one wall each, alternating
    z = round(z_first - (j - 7) * step, 1)
    side = -1 if j % 2 == 0 else 1
    x, r = side * WALL_X, -side * WALL_R
    if j < 7:
        cards.append(card(x, 0, z, r, f'<img src="{STILLS[j % len(STILLS)]}" alt="">'))
    else:
        word = FEATURES[j - 7][0]
        src = f"assets/stills/{IMG[word]}.jpg"
        if word == "Dim.":
            inner = f'<div class="cinema"><img src="{src}" alt=""></div>' + UI[word]
        elif word == "Float.":
            inner = (f'<div class="page"><i style="width:62%"></i><i style="width:80%"></i><i style="width:48%"></i>'
                     f'<i style="width:70%"></i></div><div class="mini"><img src="{src}" alt="">'
                     '<b class="mb l"></b><b class="mb r"></b></div>')
        else:
            inner = f'<img src="{src}" alt="">' + UI[word]
        cards.append(card(x, 0, z, r, inner, "card feature"))
k = 0
for m in range(7):  # upper and lower rows, staggered
    for row, y in ((0, -395), (1, 395)):
        for side in (-1, 1):
            z = -600 - 612 * m - (306 if (side == 1) ^ (row == 1) else 0)
            cards.append(card(side * WALL_X, y, z, -side * WALL_R, f'<img src="{STILLS[(k * 5 + 3) % len(STILLS)]}" alt="">'))
            k += 1

words1 = "".join(f'<span class="w" id="t-a{i}">{w}</span> ' for i, (w, _) in enumerate(FEATURES[:4])).strip()
words2 = "".join(f'<span class="w" id="t-b{i}">{w}</span> ' for i, (w, _) in enumerate(FEATURES[4:])).strip()
times = ",".join(f"{t:.3f}" for _, t in FEATURES)

html = f"""<template>
  <!-- Generated by capture/tunnel.py; edit the script and re-run it. -->
  <style>
    @font-face {{
      font-family: "BVC Inter";
      src: url("assets/fonts/inter-opsz.woff2") format("woff2");
      font-weight: 100 900;
      font-style: normal;
    }}
    #root {{ position: absolute; inset: 0; overflow: hidden; font-family: "BVC Inter", sans-serif; color: #16161d; }}
    #t-stage {{ position: absolute; inset: 0; perspective: 1100px; perspective-origin: 50% 47%; }}
    #t-world {{ position: absolute; left: 960px; top: 508px; width: 0; height: 0; transform-style: preserve-3d; }}
    .card {{ position: absolute; left: -280px; top: -157px; width: 560px; height: 315px; border-radius: 22px; overflow: hidden;
      background: #000; box-shadow: 0 30px 60px rgba(40, 50, 120, 0.18); backface-visibility: hidden; }}
    .card > img {{ position: absolute; inset: 0; width: 100%; height: 100%; object-fit: cover; }}
    .bar {{ position: absolute; left: 0; right: 0; bottom: 0; height: 7px; background: rgb(255 255 255 / 0.22); }}
    .bar i {{ position: absolute; left: 0; top: 0; bottom: 0; background: rgb(234 118 0 / 0.8); }}
    .edit {{ position: absolute; left: 14px; right: 14px; bottom: 14px; height: 26px; border-radius: 5px; background: #121a2ee8; border: 1px solid #a4c4ff; }}
    .range {{ position: absolute; left: 30%; width: 32%; top: -2px; bottom: -2px; border: 2px solid #f3cd45; background: #f3cd4555; }}
    .range b {{ position: absolute; top: -3px; bottom: -3px; width: 10px; background: #f3cd45; }}
    .range .h1 {{ left: -11px; border-radius: 4px 0 0 4px; }}
    .range .h2 {{ right: -11px; border-radius: 0 4px 4px 0; }}
    .marker {{ position: absolute; left: 43%; bottom: 0; width: 10px; height: 16px; border-radius: 2px; background: #38d9ff; border: 1px solid #06333f; }}
    .pill, .chip {{ position: absolute; display: flex; align-items: center; gap: 8px; padding: 8px 14px; border-radius: 999px;
      background: rgba(21, 26, 36, 0.9); border: 1px solid #ffffff30; color: #fff; font-size: 17px; font-weight: 600; white-space: nowrap; }}
    .pill svg, .chip svg {{ width: 20px; height: 20px; }}
    .pill b {{ color: #f3cd45; }}
    .pill img {{ width: 54px; height: 30px; border-radius: 5px; object-fit: cover; }}
    .vol {{ position: absolute; right: 16px; bottom: 26px; width: 26px; height: 90px; border-radius: 13px; overflow: hidden; background: rgb(255 255 255 / 0.25); }}
    .vol i {{ position: absolute; inset: 0; background: #fff; }}
    .cinema {{ position: absolute; inset: 0; background: #000; }}
    .cinema img {{ position: absolute; left: 13%; top: 13%; width: 74%; height: 74%; object-fit: cover; border-radius: 8px; }}
    .flash {{ position: absolute; inset: 0; background: rgba(255, 255, 255, 0.35); }}
    .page {{ position: absolute; inset: 0; background: #eceef4; padding: 30px 34px; }}
    .page i {{ display: block; height: 16px; border-radius: 8px; background: #d9dce8; margin-bottom: 18px; }}
    .mini {{ position: absolute; right: 18px; bottom: 18px; width: 232px; height: 130px; border-radius: 8px; overflow: hidden; box-shadow: 0 10px 24px rgba(0, 0, 0, 0.25); }}
    .mini img {{ width: 100%; height: 100%; object-fit: cover; }}
    .mini .mb {{ position: absolute; top: 7px; width: 22px; height: 22px; border-radius: 6px; background: rgba(255, 255, 255, 0.3); }}
    .mini .l {{ left: 7px; }}
    .mini .r {{ right: 7px; }}
    #t-veil {{ position: absolute; inset: 0; background: radial-gradient(38% 34% at 50% 47%, rgba(244, 244, 251, 0.96) 0%, rgba(244, 244, 251, 0.75) 55%, rgba(244, 244, 251, 0) 100%); }}
    .hlw {{ position: absolute; left: 0; right: 0; top: 446px; text-align: center; z-index: 5; }}
    .hl {{ display: inline-block; font-size: 104px; font-weight: 560; letter-spacing: -0.035em; line-height: 1.14; white-space: nowrap;
      font-variation-settings: "opsz" 32; }}
    .rv {{ --p: -18; -webkit-mask-image: linear-gradient(90deg, #000 calc(var(--p) * 1%), transparent calc(var(--p) * 1% + 18%));
      mask-image: linear-gradient(90deg, #000 calc(var(--p) * 1%), transparent calc(var(--p) * 1% + 18%)); }}
    .g, .w {{ background: linear-gradient(90deg, #64a8fb, #3d75fe 50%, #7b34e9); -webkit-background-clip: text; background-clip: text;
      color: transparent; padding: 0 0.04em 0.08em 0; }}
    .w {{ display: inline-block; opacity: 0; }}
  </style>
  <div id="root" data-composition-id="tunnel" data-width="1920" data-height="1080">
    <div id="t-stage" data-layout-ignore>
      <div id="t-world">
        {chr(10).join('        ' + c for c in cards).strip()}
      </div>
    </div>
    <div id="t-veil" data-layout-ignore></div>
    <div class="hlw"><h1 id="t-l1" class="hl rv">Every control <span class="g">you missed.</span></h1></div>
    <div class="hlw"><h1 id="t-l2" class="hl">{words1}</h1></div>
    <div class="hlw"><h1 id="t-l3" class="hl">{words2}</h1></div>
  </div>
  <script>
    (function () {{
      const tl = gsap.timeline({{ paused: true }});
      const times = [{times}];
      // The camera dollies down the corridor at a constant {SPEED} px/s.
      tl.fromTo("#t-world", {{ z: 0 }}, {{ z: {round(SPEED * 4.177)}, duration: 4.177, ease: "none" }}, 0);
      tl.fromTo("#t-stage", {{ opacity: 0 }}, {{ opacity: 1, duration: 0.25, ease: "power2.out" }}, 0);
      tl.fromTo("#t-l1", {{ "--p": -18, filter: "blur(10px)" }}, {{ "--p": 100, filter: "blur(0px)", duration: 0.5, ease: "power2.out" }}, 0.12);
      tl.fromTo("#t-l1", {{ opacity: 1, filter: "blur(0px)" }}, {{ opacity: 0, filter: "blur(10px)", duration: 0.16, ease: "power2.in", immediateRender: false }}, times[0] - 0.12);
      // One word per half beat, each as its card passes the lens.
      const ids = ["#t-a0", "#t-a1", "#t-a2", "#t-a3", "#t-b0", "#t-b1", "#t-b2", "#t-b3"];
      ids.forEach((id, i) =>
        tl.fromTo(id, {{ opacity: 0, y: 34, filter: "blur(8px)" }}, {{ opacity: 1, y: 0, filter: "blur(0px)", duration: 0.2, ease: "expo.out" }}, times[i]),
      );
      tl.to("#t-l2 .w", {{ opacity: 0, filter: "blur(10px)", duration: 0.14, stagger: 0.02, ease: "power2.in" }}, times[4] - 0.14);
      tl.to("#t-l3 .w", {{ opacity: 0, filter: "blur(10px)", duration: 0.14, stagger: 0.02, ease: "power2.in" }}, 4.177 - 0.2);
      tl.to(["#t-stage", "#t-veil"], {{ opacity: 0, filter: "blur(12px)", duration: 0.2, ease: "power2.in" }}, 4.177 - 0.21);

      window.__timelines["tunnel"] = tl;
    }})();
  </script>
</template>
"""
open(os.path.join(ROOT, "compositions", "tunnel.html"), "w").write(html)
print(len(cards), "cards")
